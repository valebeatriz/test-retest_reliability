%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%%%%%%%% step4_RUN_ALL_truncation.m
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%
% For every (subjects x volumes x session type) combination, runs
% num_internal_iterations draws of random subjects, using the fixed first-N-volumes
% data from step3. Cheapest of the three sweeps: stage1 caches each subject's FC.
%
% Requires step1, step2 and step3 (parcellated_data_300/600/900/1200).
%
%% Adapts code from:
% FC matrices: https://github.com/isesteves/multilevel-fingerprinting_migraine/tree/main
% Fingerprinting: https://github.com/eamico/Clinical_fingerprinting
% Discriminability: https://github.com/RXRodriguez98/DiscriminabilityMATLAB/tree/main

clear all;
clc;

paths = project_paths();

% --- Global Configuration Parameters ---
subject_number_options = [10, 20, 50, 80];
volumes_number_options = [300, 600, 900, 1200];
type_session_options = {'INTER', 'INTRA'};

num_internal_iterations = 100;

% --- Paths and Pipeline Step (Constant across all runs) ---
config_path = paths.config;
pipeline_step = 'step2_sFC_Pearson';
output_base_path = fullfile(paths.data, 'derivatives', 'ICC_Idiff_Discr');
if ~exist(output_base_path, 'dir')
    mkdir(output_base_path);
end

% --- Master List of All Subjects ---
all_HCP_master_subjects = {'100307', '100408', '101107', '101309', '101915', '103111', '103414', '103818', '105014', '105115', '106016', '108828', '110411', '111312', '111716', '113619', '113922', '114419', '115320', '116524', '117122', '118528', '118730', '118932', '120111', '122317', '122620', '123117', '123925', '124422', '125525', '126325', '127630', '127933', '128127', '128632', '129028', '130013', '130316', '131217', '131722', '133019', '133928', '135225', '135932', '136833', '138534', '139637', '140925', '144832', '146432', '147737', '148335', '148840', '149337', '149539', '149741', '151223', '151526', '151627', '153025', '154734', '156637', '159340', '160123', '161731', '162733', '163129', '176542', '178950', '188347', '189450', '190031', '192540', '196750', '198451', '199655', '201111', '208226', '211417', '211720', '212318', '214423', '221319', '239944', '245333', '280739', '298051', '366446', '397760', '414229', '499566', '654754', '672756', '751348', '756055', '792564', '856766', '857263', '899885'};

% --- Outer Loops for Parameter Combinations ---
for current_subject_number = subject_number_options
    for current_volumes_number = volumes_number_options
        for current_type_session_cell = type_session_options
            current_type_session = current_type_session_cell{1};

            fprintf('\n--- Running Combination: Subjects=%d, Volumes=%d, SessionType=%s ---\n', ...
                current_subject_number, current_volumes_number, current_type_session);

            results = struct();

            % --- Inner Loop for Monte Carlo Iterations ---
            for z = 1:num_internal_iterations
                fprintf('  Iteration %d of %d for current combination...\n', z, num_internal_iterations);

                % Clear variables generated by pipeline scripts for a fresh start each iteration.
                clear Idiff discr_value network_icc_means subjects;

                %% Subject and Session Selection for the current iteration
                rng('shuffle');
                random_indices = randperm(length(all_HCP_master_subjects), current_subject_number);
                HCP_selected_subjects = all_HCP_master_subjects(random_indices);

                % Determine sessions based on current_type_session
                if strcmp(current_type_session, 'INTRA')
                    all_HCP_subjects_config = {HCP_selected_subjects; HCP_selected_subjects};  % Two sets for INTRA
                    all_sessions = {'rfMRI_REST1_LR', 'rfMRI_REST1_RL'};
                    config_subjects_list = all_HCP_subjects_config;

                elseif strcmp(current_type_session, 'INTER')
                    % Individual batches per subject, each with its own session (alternating LR/RL).
                    all_HCP_subjects_config = {};
                    all_sessions = {};

                    % First pass: first session per subject (alternating LR/RL)
                    for i = 1:length(HCP_selected_subjects)
                        all_HCP_subjects_config{end+1} = {HCP_selected_subjects{i}};
                        if mod(i, 2) == 1
                            all_sessions{end+1} = 'rfMRI_REST1_LR';
                        else
                            all_sessions{end+1} = 'rfMRI_REST1_RL';
                        end
                    end

                    % Second pass: second session per subject (alternating RL/LR)
                    for i = 1:length(HCP_selected_subjects)
                        all_HCP_subjects_config{end+1} = {HCP_selected_subjects{i}};
                        if mod(i, 2) == 1
                            all_sessions{end+1} = 'rfMRI_REST2_RL';
                        else
                            all_sessions{end+1} = 'rfMRI_REST2_LR';
                        end
                    end

                    config_subjects_list = all_HCP_subjects_config;

                else
                    error('Invalid type_session. Must be ''INTER'' or ''INTRA''.');
                end

                %% Create Configuration File for Pipeline
                config = struct();
                config.in_path = fullfile(paths.data, 'derivatives', sprintf('parcellated_data_%d', current_volumes_number));
                config.out_path = fullfile(paths.data, 'derivatives', sprintf('sFC_Pearson_%d_%s', current_volumes_number, current_type_session));
                config.pipelinelog_path = paths.logs;
                config.subjects = config_subjects_list;
                config.Nsubjects = current_subject_number * 2;
                config.sessions = all_sessions;
                config.pipelines = {num2str(current_volumes_number)};
                config.session_type = {current_type_session};
                config.atlases = {'Schaefernew7400'};
                config.atlases_Nareas = 400;
                config.TR = 0.72;
                config.nr_windows = 1;
                config.include_areas = 1:400;
                config.include_Nareas = 400;
                config.order_bysubject = 1:current_subject_number * 2;

                save(fullfile(config_path, [pipeline_step, '_config.mat']), 'config');
                config_tracker(config_path, pipeline_step, config);

                %% Run Pipeline Steps
                disp('    Stage 1 - Connectivity Matrix');
                run(fullfile(paths.scripts, 'stage1_sFC_Pearson_truncation.m'));

                disp('    Stage 1b - Transform matrix');
                run(fullfile(paths.scripts, 'stage1b_transform_FC_fisher.m'));

                disp('    Stage 2 - Fingerprinting');
                run(fullfile(paths.scripts, 'stage2_FC_fingerprint.m'));

                close all;

                disp('    Stage 3 - Edge-level ICC');
                run(fullfile(paths.scripts, 'stage3_ICC_edge_mean.m'));

                disp('    Stage 4 - Discriminability');
                run(fullfile(paths.scripts, 'stage4_discriminability.m'));

                disp('    Stage 5 - Connectome-level ICC');
                run(fullfile(paths.scripts, 'stage5_ICC_connectome_level.m'));

                % --- Store Results for Current Iteration ---
                % Idiff, discr_value, network_icc_means, and subjects should be
                % in the workspace after the run() calls above; guard against a
                % failed run leaving them missing.
                if exist('Idiff', 'var') && exist('discr_value', 'var') && exist('network_icc_means', 'var') && exist('subjects', 'var')
                    results(z).Idiff = Idiff;
                    results(z).discr_value = discr_value;
                    results(z).network_icc_means = network_icc_means;
                    results(z).ICC_individual = ICC_individual_FC;
                    results(z).Iself = Iself;
                    results(z).sr_mean = sr_mean;

                    if iscell(subjects) && ~isempty(subjects)
                        results(z).subjects = subjects{1};
                    else
                        results(z).subjects = subjects;  % fallback if subjects isn't a cell array
                    end
                else
                    warning('Skipping results storage for iteration %d due to missing variables.', z);
                    results(z).Idiff = [];
                    results(z).discr_value = [];
                    results(z).network_icc_means = [];
                    results(z).subjects = {};
                end

            end % End of num_internal_iterations loop

            % --- Save All Aggregated Results for this Combination ---
            output_filename = fullfile(output_base_path, sprintf('%dsubs_%dvol_%s_TRUNCATION.mat', ...
                current_subject_number, current_volumes_number, current_type_session));
            save(output_filename, 'results');

            fprintf('  Results for this combination saved to: %s\n', output_filename);

        end % End of type_session_options loop
    end % End of volumes_number_options loop
end % End of subject_number_options loop

fprintf('\nAll pipeline combinations complete.\n');
